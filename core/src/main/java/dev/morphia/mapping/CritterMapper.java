import static dev.morphia.critter.Critter.critterPackage;

/**
 * Hybrid mapper using three-tier entity model discovery:
 * <ol>
 * <li>Pre-generated models from the classpath (critter-maven AOT)</li>
 * <li>Runtime bytecode generation, using hidden nestmate accessors</li>
 * <li>Reflection-based fallback</li>
 * </ol>
 *
 * @morphia.internal
 * @hidden
 */
@MorphiaInternal
public class CritterMapper extends AbstractMapper {
    private static final Logger LOG = LoggerFactory.getLogger(CritterMapper.class);

    /**
     * Morphia's stateless strategies: every instance of one of these classes behaves the same, so configurations using
     * them can be compared by class.
     */
    private static final Set<Class<?>> BUILT_IN_STRATEGIES = Set.of(
            NamingStrategy.identity().getClass(),
            NamingStrategy.lowerCase().getClass(),
            NamingStrategy.snakeCase().getClass(),
            NamingStrategy.camelCase().getClass(),
            NamingStrategy.kebabCase().getClass(),
            NamingStrategy.title().getClass(),
            DiscriminatorFunction.className().getClass(),
            DiscriminatorFunction.lowerClassName().getClass(),
            DiscriminatorFunction.lowerSimpleName().getClass(),
            DiscriminatorFunction.simpleName().getClass(),
            MorphiaPropertyAnnotationProvider.class);

    /**
     * Each entity's pre-generated model, or empty if critter-maven didn't generate a usable one for it. Whether a usable
     * model exists doesn't depend on a mapper's configuration, so the lookup is made once per class.
     */
    private static final ClassValue<Optional<Pregenerated>> PREGENERATED = new ClassValue<>() {
        @Override
        protected Optional<Pregenerated> computeValue(Class<?> type) {
            String modelClassName = critterPackage(type) + "." + type.getSimpleName() + "EntityModel";
            try {
                Class<?> modelClass = Class.forName(modelClassName, true, type.getClassLoader());
                String version = constant(modelClass, CritterEntityModel.MORPHIA_VERSION_FIELD);
                if (!CritterEntityModel.MORPHIA_VERSION.equals(version)) {
                    return ignored(type, "it was generated by Morphia %s, but this is Morphia %s"
                            .formatted(version, CritterEntityModel.MORPHIA_VERSION));
                }
                String buildId = constant(modelClass, CritterEntityModel.BUILD_ID);
                for (String woven : constant(modelClass, CritterEntityModel.WOVEN_CLASSES).split(",")) {
                    if (!CritterEntityModel.isWovenBy(type, woven, buildId)) {
                        return ignored(type, woven + " was compiled again, or woven by another critter-maven run, after the "
                                + "model was generated");
                    }
                }
                return Optional.of(new Pregenerated(modelClass.getConstructor(Mapper.class),
                        constant(modelClass, CritterEntityModel.GENERATION_KEY)));
            } catch (ClassNotFoundException e) {
                return Optional.empty();
            } catch (NoSuchFieldException e) {
                return ignored(type, "it was generated by an earlier version of critter-maven");
            } catch (ReflectiveOperationException | LinkageError e) {
                LOG.warn("Failed to load pre-generated model for {}: {}", type.getName(), e.getMessage());
                return Optional.empty();
            }
        }
    };

    private static String constant(Class<?> modelClass, String name) throws ReflectiveOperationException {
        return (String) modelClass.getField(name).get(null);
    }

    private static Optional<Pregenerated> ignored(Class<?> type, String reason) {
        LOG.warn("Ignoring the pre-generated model for {}: {}. Its model is generated at runtime instead; rebuild with "
                + "critter-maven to use it.", type.getName(), reason);
        return Optional.empty();
    }

    /**
     * The mismatches with pre-generated models already logged: pairs of generation keys, or the key of a configuration that
     * can't be compared.
     */
    private static final Set<String> LOGGED_MISMATCHES = ConcurrentHashMap.newKeySet();

    /**
     * A pre-generated model.
     *
     * @param constructor   its constructor
     * @param generationKey the generation key of the configuration it was generated with
     */
    private record Pregenerated(Constructor<?> constructor, String generationKey) {
    }

    private final RuntimeModels runtimeModels;
    private final CritterGenerator generator;
    private final String generationKey;
    // the generation key if this mapper's configuration can be compared with a pre-generated model's
    @Nullable
    private final String comparableKey;

    /**
     * Creates a CritterMapper with the given config.
     *
     * @param config the config to use
     * @hidden
     * @morphia.internal
     */
    @MorphiaInternal
    public CritterMapper(MorphiaConfig config) {
        this(config, Thread.currentThread().getContextClassLoader());
    }

    /**
     * Creates a CritterMapper with the given config.
     *
     * @param config      the config to use
     * @param classLoader the class loader to use for loading generated classes
     * @hidden
     * @morphia.internal
     */
    @MorphiaInternal
    public CritterMapper(MorphiaConfig config, ClassLoader classLoader) {
        super(config, classLoader);
        this.generationKey = CritterEntityModel.generationKey(config);
        this.comparableKey = comparableKey(config, generationKey);
        this.runtimeModels = RuntimeModels.forConfig(config, generationKey, classLoader);
        this.generator = new CritterGenerator(this);
    }

    /**
     * Copy constructor — shares immutable CritterEntityModel references,
     * creates a new DiscriminatorLookup for session isolation.
     * <p>
     * Note: calls {@code super(config, classLoader)} rather than {@code super(other)} because
     * {@code AbstractMapper}'s copy constructor calls {@code new EntityModel(original)} for every
     * entity, which is incorrect for {@code CritterEntityModel}. As a side effect, this creates a
     * fresh {@code Conversions} instance instead of sharing {@code other.conversions}. Any custom
     * converters registered on the original mapper after construction will not be visible in the
     * copy. If sharing custom converters becomes necessary, consider adding a package-private
     * accessor on {@code AbstractMapper} for its {@code conversions} field.
     * </p>
     *
     * @param other the original to copy
     * @hidden
     * @morphia.internal
     */
    @MorphiaInternal
    public CritterMapper(CritterMapper other) {
        this(other, other.config);
    }

    /**
     * Copy constructor that reuses another mapper's entity graph under a different config
     * (e.g. a different database name) — see {@link #CritterMapper(CritterMapper)} for why
     * this shares immutable {@code CritterEntityModel} references and creates a new
     * {@code DiscriminatorLookup} rather than delegating to {@code AbstractMapper}'s copy
     * constructor.
     * <p>
     * Already-mapped entities are cloned as they are. Entities mapped later through the copy reuse the original's
     * runtime-generated classes only if {@code config} generates the same bytecode (same naming, discriminator, property
     * discovery and annotation providers); otherwise the copy generates its own.
     * </p>
     *
     * @param other  the original to clone the entity graph from
     * @param config the config the new mapper should report/operate under
     * @hidden
     * @morphia.internal
     */
    @MorphiaInternal
    public CritterMapper(CritterMapper other, MorphiaConfig config) {
        super(config, other.classLoader);
        this.generationKey = CritterEntityModel.generationKey(config);
        this.comparableKey = comparableKey(config, generationKey);
        this.runtimeModels = RuntimeModels.forCopy(other.runtimeModels, other.config, other.generationKey, config, generationKey,
                other.classLoader);
        this.generator = new CritterGenerator(this);
        // Create independent copies of all entity models so that each mapper instance
        // maintains its own model state (e.g. listeners, version tracking).
        other.mappedEntities.values().forEach(model -> {
            if (model instanceof CritterEntityModel) {
                try {
                    java.lang.reflect.Constructor<?> ctor = model.getClass().getConstructor(Mapper.class);
                    register((EntityModel) ctor.newInstance(this), false);
                } catch (Exception e) {
                    LOG.warn("Failed to clone CritterEntityModel for {}; sharing reference: {}",
                            model.getType().getName(), e.getMessage());
                    register(model, false);
                }
            } else {
                register(new EntityModel(model), false);
            }
        });
        copyStandIns(other);
    }

    @Override
    public Mapper copy() {
        return new CritterMapper(this);
    }

    @Override
    protected EntityModel buildModel(Class<?> type) {
        EntityModel model = tryLoadPregenerated(type);
        if (model == null) {
            model = tryRuntimeGeneration(type);
        }
        return model != null ? model : fallbackToReflection(type);
    }

    /**
     * Tier 1: Attempt to load a pre-generated model class placed on the classpath
     * by critter-maven. The naming convention is:
     * {@code {package}.__morphia.{simpleNameLowercase}.{SimpleName}EntityModel}.
     * A model generated with a configuration that names or discovers properties differently than this mapper's isn't used.
     */
    @Nullable
    private EntityModel tryLoadPregenerated(Class<?> type) {
        Pregenerated pregenerated = PREGENERATED.get(type).orElse(null);
        if (pregenerated == null) {
            return null;
        }
        if (comparableKey == null) {
            if (LOGGED_MISMATCHES.add(generationKey)) {
                LOG.warn("Ignoring pre-generated models: this mapper's configuration uses a naming or discriminator strategy, or "
                        + "property annotation provider, other than Morphia's built-ins, so it can't be checked against theirs. Their "
                        + "models are generated at runtime instead. This mapper's: {}.", generationKey);
            }
            return null;
        }
        if (!pregenerated.generationKey().equals(comparableKey)) {
            if (LOGGED_MISMATCHES.add(pregenerated.generationKey() + "\n" + comparableKey)) {
                LOG.warn("Ignoring pre-generated models built with a different mapping configuration than this mapper's; their "
                        + "models are generated at runtime instead. Built with: {}. This mapper's: {}.",
                        pregenerated.generationKey(), comparableKey);
            }
            return null;
        }
        try {
            return (EntityModel) pregenerated.constructor().newInstance(this);
        } catch (Throwable e) {
            LOG.warn("Failed to load pre-generated model for {}: {}", type.getName(), e.getMessage());
            return null;
        }
    }

    /**
     * Tier 2: Generate an entity model at runtime, using hidden nestmate accessor classes for property access.
     * Returns null so the caller falls through to reflection if generation fails. A failure is remembered, and logged
     * once, for every mapper sharing the runtime models: they generate the same bytecode, so they would fail the same way.
     */
    @Nullable
    private EntityModel tryRuntimeGeneration(Class<?> type) {
        Class<?> modelClass;
        try {
            modelClass = runtimeModels.modelClass(type, generator);
        } catch (Exception e) {
            NestmateAccessException accessFailure = accessFailure(e);
            if (accessFailure != null) {
                LOG.warn("Runtime critter generation can't access {} because it isn't in Morphia's module (on the classpath: "
                        + "it's loaded by a different class loader than Morphia); falling back to reflection. To use critter "
                        + "models for it, pre-generate them at build time with the critter-maven plugin. Cause: {}",
                        accessFailure.getType().getName(), accessFailure.getCause().getMessage());
            } else {
                LOG.warn("Runtime bytecode generation failed for {}; falling back to reflection: {}",
                        type.getName(), e.getMessage(), e);
            }
            return null;
        }
        if (modelClass == null) {
            return null;
        }
        try {
            return (EntityModel) modelClass.getConstructor(Mapper.class).newInstance(this);
        } catch (Exception e) {
            LOG.warn("Failed to create the runtime-generated model for {}; falling back to reflection: {}",
                    type.getName(), e.getMessage(), e);
            return null;
        }
    }

    /**
     * @param e the runtime generation failure
     * @return the {@link NestmateAccessException} in {@code e}'s cause chain if runtime generation failed because Morphia
     *         can't access the entity's module, or null if it failed for another reason
     */
    @Nullable
    static NestmateAccessException accessFailure(Throwable e) {
        Set<Throwable> seen = Collections.newSetFromMap(new IdentityHashMap<>());
        for (Throwable t = e; t != null && seen.add(t); t = t.getCause()) {
            if (t instanceof NestmateAccessException accessException) {
                return accessException;
            }
        }
        return null;
    }

    /**
     * Tier 3: Fall back to the standard reflection-based EntityModel.
     */
    private EntityModel fallbackToReflection(Class<?> type) {
        return new ReflectiveEntityModelBuilder(this, type).build();
    }

    /**
     * The runtime-generated model classes for one parent class loader and mapping configuration. The
     * {@link CritterClassLoader} is created the first time a model has to be generated at runtime; when every model is
     * pre-generated, it is never needed.
     * <p>
     * Copies of a mapper share the same instance unless the copy's configuration generates different bytecode. So do separate mappers with
     * the same parent loader and an equivalent
     * configuration (see {@link #comparableKey(MorphiaConfig, String)}), so each entity is generated once rather than once per
     * mapper. Instances are cached weakly: once no mapper refers to one, its loader and classes can be collected.
     */
    private static final class RuntimeModels {
        private static final Map<ClassLoader, Map<String, WeakReference<RuntimeModels>>> SHARED = new WeakHashMap<>();

        private final ClassLoader parent;
        private final Map<Class<?>, Class<?>> modelClasses = new HashMap<>();
        // the types whose generation failed
        private final Set<Class<?>> failures = new HashSet<>();
        @Nullable
        private CritterClassLoader loader;

        private RuntimeModels(ClassLoader parent) {
            this.parent = parent;
            this.loader = parent instanceof CritterClassLoader ccl ? ccl : null;
        }

        /**
         * @return the shared instance for this loader and configuration, or a new unshared one if the configuration
         *         can't be compared safely or {@code parent} is itself a {@link CritterClassLoader}
         */
        private static RuntimeModels forConfig(MorphiaConfig config, String generationKey, ClassLoader parent) {
            String key = parent instanceof CritterClassLoader ? null : comparableKey(config, generationKey);
            if (key == null) {
                return new RuntimeModels(parent);
            }
            synchronized (SHARED) {
                Map<String, WeakReference<RuntimeModels>> byConfig = SHARED.computeIfAbsent(parent, p -> new HashMap<>());
                byConfig.values().removeIf(ref -> ref.get() == null);
                WeakReference<RuntimeModels> ref = byConfig.get(key);
                RuntimeModels models = ref != null ? ref.get() : null;
                if (models == null) {
                    models = new RuntimeModels(parent);
                    byConfig.put(key, new WeakReference<>(models));
                }
                return models;
            }
        }

        /**
         * Picks the runtime models for a copy of a mapper. The copy keeps the original's instance when its configuration
         * generates the same bytecode; otherwise entities first mapped through the copy would get classes generated under
         * the original's settings.
         *
         * @param original              the original mapper's runtime models
         * @param originalConfig        the original mapper's configuration
         * @param originalGenerationKey the original configuration's generation key
         * @param config                the copy's configuration
         * @param generationKey         the copy's configuration's generation key
         * @param parent                the parent class loader
         * @return the runtime models for the copy
         */
        private static RuntimeModels forCopy(RuntimeModels original, MorphiaConfig originalConfig, String originalGenerationKey,
                MorphiaConfig config, String generationKey, ClassLoader parent) {
            if (config == originalConfig) {
                return original;
            }
            String originalKey = comparableKey(originalConfig, originalGenerationKey);
            if (originalKey != null && originalKey.equals(comparableKey(config, generationKey))) {
                return original;
            }
            if (parent instanceof CritterClassLoader) {
                // The original may already have defined its models in this loader under the same names, and the loader
                // would hand those back; generate the copy's models in a child loader of their own.
                return new RuntimeModels(new CritterClassLoader(parent));
            }
            return forConfig(config, generationKey, parent);
        }

        /**
         * Returns the model class for {@code type}, generating it the first time any mapper sharing this instance asks.
         *
         * @return the model class, or null if generating it failed before
         * @throws Exception if generating it fails now, which is remembered so it isn't tried again
         */
        @Nullable
        private synchronized Class<?> modelClass(Class<?> type, CritterGenerator generator) throws Exception {
            if (failures.contains(type)) {
                return null;
            }
            Class<?> modelClass = modelClasses.get(type);
            if (modelClass == null) {
                try {
                    CritterClassLoader target = loaderFor(type);
                    EntityModelGenerator entityModel = generator.generate(type, target, true);
                    modelClass = target.loadClass(entityModel.getGeneratedType());
                } catch (Exception e) {
                    failures.add(type);
                    throw e;
                }
                modelClasses.put(type, modelClass);
            }
            return modelClass;
        }

        /**
         * Generated class names come from the persisted type, so two {@code @ExternalEntity} stand-ins for the same target
         * would collide in one loader. Each stand-in gets a loader of its own.
         */
        private CritterClassLoader loaderFor(Class<?> type) {
            if (ClassHierarchy.annotations(type).containsKey(ExternalEntity.class)) {
                return new CritterClassLoader(parent);
            }
            if (loader == null) {
                loader = new CritterClassLoader(parent);
            }
            return loader;
        }
    }

    /**
     * The generation key when it identifies what generation bakes into a model. Two configurations with equal keys then
     * produce identical models: their mappers can share runtime-generated classes, and a pre-generated model can be used
     * with either.
     *
     * @param config        the configuration
     * @param generationKey its generation key
     * @return the {@link CritterEntityModel#generationKey(MorphiaConfig) generation key}, or {@code null} if a strategy isn't one
     *         of Morphia's stateless built-ins, in which case two instances of the same class could still behave differently
     *         (e.g. a naming strategy with a configurable prefix)
     */
    @Nullable
    private static String comparableKey(MorphiaConfig config, String generationKey) {
        List<Object> strategies = new ArrayList<>();
        strategies.add(config.collectionNaming());
        strategies.add(config.propertyNaming());
        strategies.add(config.discriminator());
        strategies.addAll(config.propertyAnnotationProviders());
        for (Object strategy : strategies) {
            if (!BUILT_IN_STRATEGIES.contains(strategy.getClass())) {
                return null;
            }
        }
        return generationKey;
    }
}
