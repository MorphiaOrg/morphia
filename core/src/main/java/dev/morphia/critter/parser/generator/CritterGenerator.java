package dev.morphia.critter.parser.generator;

import java.lang.invoke.MethodHandles;
import java.lang.invoke.MethodHandles.Lookup;
import java.lang.reflect.Constructor;
import java.lang.reflect.Modifier;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.stream.Collectors;

import dev.morphia.annotations.ExternalEntity;
import dev.morphia.critter.CritterClassLoader;
import dev.morphia.critter.parser.FieldInfo;
import dev.morphia.critter.parser.MethodInfo;
import dev.morphia.critter.parser.PropertyFinder;
import dev.morphia.critter.parser.PropertyFinder.Properties;
import dev.morphia.mapping.Mapper;
import dev.morphia.mapping.codec.pojo.ClassHierarchy;
import dev.morphia.mapping.internal.ConstructorCreator;

import org.bson.codecs.pojo.PropertyAccessor;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import io.smallrye.classfile.ClassFile;
import io.smallrye.classfile.ClassModel;

/**
 * Facade that orchestrates the full ClassFile-based code generation pipeline for a Morphia entity,
 * including field/method accessor injection and property/entity model generation.
 */
public class CritterGenerator {
    private static final Logger LOG = LoggerFactory.getLogger(CritterGenerator.class);
    private final Mapper mapper;
    // stamped on every class this generator weaves and recorded in every model it generates at build time
    private final String buildId = BuildStamp.newId();

    /**
     * Creates a new CritterGenerator with the given mapper.
     *
     * @param mapper the Morphia mapper
     */
    public CritterGenerator(Mapper mapper) {
        this.mapper = mapper;
    }

    /**
     * Reads the entity class bytecode, discovers its properties, and generates all required Critter support classes.
     *
     * @param type               the entity class to process
     * @param critterClassLoader the class loader that will receive generated bytecode
     * @param runtimeMode        {@code true} to generate hidden nestmate accessors for runtime use
     * @return the generated entity model generator
     */
    public EntityModelGenerator generate(Class<?> type, CritterClassLoader critterClassLoader, boolean runtimeMode) {
        // For @ExternalEntity, the annotated stand-in class describes the mapping; the target
        // class is what actually gets persisted and needs accessor/model generation.
        ExternalEntity ext = (ExternalEntity) ClassHierarchy.annotations(type).get(ExternalEntity.class);
        Class<?> standinType = type;
        Class<?> targetType = ext != null ? ext.target() : type;

        Properties properties = new PropertyFinder(this, mapper, critterClassLoader, runtimeMode).find(standinType, targetType);
        // at build time, the woven entity calls the constructors, and each instantiator is named for the woven method it calls
        List<String> woven = runtimeMode ? null
                : InstantiatorGenerator.wovenConstructors(ClassFile.of().parse(properties.classes().get(targetType.getName())));
        List<InstantiatorGenerator> instantiators = instantiators(targetType, properties.models(), critterClassLoader, woven);
        Runnable defineInstantiators = runtimeMode ? nestmateInstantiators(critterClassLoader, targetType, instantiators) : null;
        if (defineInstantiators == null && runtimeMode) {
            instantiators = List.of();
        }
        EntityModelGenerator entityModel = new EntityModelGenerator(mapper, targetType, standinType, critterClassLoader,
                properties.models()).instantiators(instantiators);
        if (!runtimeMode) {
            entityModel.pregenerated(buildId, properties.classes().entrySet().stream()
                    .filter(e -> BuildStamp.isStamped(e.getValue()))
                    .map(Map.Entry::getKey)
                    .toList());
        }
        // nothing is emitted until every class has been generated
        byte[] model = entityModel.generate();
        if (!runtimeMode) {
            for (InstantiatorGenerator instantiator : instantiators) {
                properties.classes().put(instantiator.getGeneratedType(), instantiator.generate());
            }
        }
        properties.accessors().run();
        if (defineInstantiators != null) {
            defineInstantiators.run();
        }
        critterClassLoader.register(entityModel.getGeneratedType(), model);
        return entityModel;
    }

    /**
     * @return an instantiator for each constructor decoding may choose: the no-arg constructor and those whose parameters
     *         all name properties. None for a type that can't be instantiated, or, at build time, whose woven methods the
     *         instantiators can't call; its instances are created reflectively.
     */
    private static List<InstantiatorGenerator> instantiators(Class<?> type, List<PropertyModelGenerator> properties,
            CritterClassLoader critterClassLoader, List<String> woven) {
        boolean runtimeMode = woven == null;
        int modifiers = type.getModifiers();
        if (Modifier.isAbstract(modifiers) || type.isInterface() || type.isEnum()
                || (type.isMemberClass() && !Modifier.isStatic(modifiers))
                || (!runtimeMode && !InstantiatorGenerator.isAccessible(type))) {
            return List.of();
        }
        Set<String> names = properties.stream().map(PropertyModelGenerator::getPropertyName).collect(Collectors.toSet());
        List<InstantiatorGenerator> instantiators = new ArrayList<>();
        for (Constructor<?> constructor : type.getDeclaredConstructors()) {
            if (!constructor.isSynthetic() && Arrays.stream(constructor.getParameters())
                    .allMatch(parameter -> names.contains(ConstructorCreator.getParameterName(parameter)))) {
                int index = runtimeMode ? instantiators.size()
                        : woven.indexOf(InstantiatorGenerator.descriptor(constructor));
                if (index >= 0) {
                    instantiators.add(new InstantiatorGenerator(type, critterClassLoader, constructor, index, runtimeMode));
                }
            }
        }
        return instantiators;
    }

    /**
     * Prepares the entity's hidden nestmate instantiators, registered in {@link NestmateAccessorRegistry} when defined.
     *
     * @return defines and registers the instantiators, or null if Morphia can't define nestmates in the entity, which is then
     *         instantiated reflectively
     */
    private static Runnable nestmateInstantiators(CritterClassLoader critterClassLoader, Class<?> type,
            List<InstantiatorGenerator> instantiators) {
        if (instantiators.isEmpty()) {
            return () -> {
            };
        }
        Lookup lookup;
        try {
            lookup = privateLookup(type);
        } catch (NestmateAccessException e) {
            LOG.debug("Critter can't generate instantiators for {}; it is instantiated reflectively", type.getName(), e);
            return null;
        }
        List<byte[]> classes = instantiators.stream().map(InstantiatorGenerator::generate).toList();
        return () -> {
            for (int i = 0; i < instantiators.size(); i++) {
                try {
                    Class<?> instantiatorClass = lookup.defineHiddenClass(classes.get(i), true, Lookup.ClassOption.NESTMATE)
                            .lookupClass();
                    NestmateAccessorRegistry.register(critterClassLoader, instantiators.get(i).registryKey,
                            instantiatorClass.getDeclaredConstructor().newInstance());
                } catch (ReflectiveOperationException e) {
                    throw new RuntimeException(e);
                }
            }
        };
    }

    /**
     * Reads the entity class bytecode, discovers its properties, and generates all required Critter support classes
     * using build-time (non-runtime) mode.
     *
     * @param type               the entity class to process
     * @param critterClassLoader the class loader that will receive generated bytecode
     * @return the generated entity model generator
     */
    public EntityModelGenerator generate(Class<?> type, CritterClassLoader critterClassLoader) {
        return generate(type, critterClassLoader, false);
    }

    /**
     * Generates bytecode augmenting the entity with synthetic {@code __readXxx}/{@code __writeXxx} methods for its fields,
     * stamped with this generator's build ID.
     *
     * @param entityType the entity class to augment
     * @param model      the entity's parsed classfile
     * @param fields     the fields for which accessor methods should be generated
     * @return the augmented class bytecode
     */
    public byte[] fieldAccessors(Class<?> entityType, ClassModel model, List<FieldInfo> fields) {
        return BuildStamp.stamp(new AddFieldAccessorMethods(entityType, model, fields).emit(), buildId);
    }

    /**
     * Generates bytecode augmenting the entity with synthetic {@code __readXxx}/{@code __writeXxx} methods for its getter methods,
     * stamped with this generator's build ID.
     *
     * @param entityType the entity class to augment
     * @param model      the entity's parsed classfile
     * @param methods    the getter methods for which accessor methods should be generated
     * @return the augmented class bytecode
     */
    public byte[] methodAccessors(Class<?> entityType, ClassModel model, List<MethodInfo> methods) {
        return BuildStamp.stamp(new AddMethodAccessorMethods(entityType, model, methods).emit(), buildId);
    }

    /**
     * Prepares hidden nestmate accessors, checking that Morphia can define every one of them before any is defined. Each
     * accessor is defined as a nestmate of the class declaring its field, or getter and setter, so it can reach private
     * members directly, and its instance is registered in {@link NestmateAccessorRegistry}.
     *
     * @param critterClassLoader the class loader that will define the generated models using the accessors
     * @param generators         the accessors' generators
     * @return defines and registers the accessors
     * @throws NestmateAccessException if Morphia can't define a nestmate in one of the classes
     */
    public Runnable nestmateAccessors(CritterClassLoader critterClassLoader, List<NestmateAccessorGenerator> generators) {
        Map<Class<?>, Lookup> lookups = new HashMap<>();
        for (NestmateAccessorGenerator generator : generators) {
            Class<?> host = generator.declaringClass;
            if (!lookups.containsKey(host)) {
                lookups.put(host, privateLookup(host));
            }
        }
        List<byte[]> classes = generators.stream().map(NestmateAccessorGenerator::generate).toList();
        return () -> {
            for (int i = 0; i < generators.size(); i++) {
                NestmateAccessorGenerator generator = generators.get(i);
                Lookup lookup = lookups.get(generator.declaringClass);
                try {
                    Class<?> accessorClass = lookup.defineHiddenClass(classes.get(i), true, Lookup.ClassOption.NESTMATE)
                            .lookupClass();
                    PropertyAccessor<?> instance = (PropertyAccessor<?>) accessorClass.getDeclaredConstructor().newInstance();
                    NestmateAccessorRegistry.register(critterClassLoader, generator.registryKey, instance);
                } catch (ReflectiveOperationException e) {
                    throw new RuntimeException(e);
                }
            }
        };
    }

    /**
     * Defining a nestmate needs full privilege access, which Morphia only has to classes in its own module.
     */
    private static Lookup privateLookup(Class<?> host) {
        try {
            Lookup lookup = MethodHandles.privateLookupIn(host, MethodHandles.lookup());
            if (!lookup.hasFullPrivilegeAccess()) {
                throw new IllegalAccessException("%s does not have full privilege access".formatted(lookup));
            }
            return lookup;
        } catch (IllegalAccessException e) {
            throw new NestmateAccessException(host, e);
        }
    }
}
