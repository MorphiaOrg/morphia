package dev.morphia.critter.parser.generator;

import java.lang.annotation.Annotation;
import java.lang.constant.ClassDesc;
import java.lang.constant.ConstantDescs;
import java.lang.constant.MethodTypeDesc;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;

import dev.morphia.annotations.Entity;
import dev.morphia.annotations.ExternalEntity;
import dev.morphia.critter.CritterClassLoader;
import dev.morphia.mapping.Mapper;
import dev.morphia.mapping.codec.pojo.ClassHierarchy;
import dev.morphia.mapping.codec.pojo.critter.CritterEntityModel;
import dev.morphia.mapping.internal.Instantiator;

import io.smallrye.classfile.ClassBuilder;
import io.smallrye.classfile.ClassFile;
import io.smallrye.classfile.CodeBuilder;
import io.smallrye.classfile.attribute.ConstantValueAttribute;

import static dev.morphia.annotations.internal.EntityBuilder.entityBuilder;

/**
 * Generates a ClassFile-based {@code CritterEntityModel} implementation for a Morphia entity class.
 */
public class EntityModelGenerator extends BaseGenerator {
    private final Mapper mapper;
    private final List<PropertyModelGenerator> properties;
    private final Entity entityAnnotation;
    private final ExternalEntity externalEntity;
    private final List<Annotation> morphiaAnnotations;
    private List<InstantiatorGenerator> instantiators = List.of();
    private List<String> weaveStamps;

    /**
     * Creates a new entity model generator for the given entity, reading entity-level annotations
     * from {@code standinType} (which differs from {@code type} only for {@code @ExternalEntity}).
     *
     * @param mapper             the Morphia mapper
     * @param type               the target class for which code is generated (instances of this type are persisted)
     * @param standinType        the class carrying the entity-level Morphia annotations; equals {@code type} for normal entities
     * @param critterClassLoader the class loader that will receive the generated bytecode
     * @param properties         the property model generators for each of the entity's properties
     * @throws IllegalStateException if neither {@code @Entity} nor {@code @ExternalEntity} is present on {@code standinType}
     */
    public EntityModelGenerator(Mapper mapper, Class<?> type, Class<?> standinType, CritterClassLoader critterClassLoader,
            List<PropertyModelGenerator> properties) {
        super(type, critterClassLoader);
        this.mapper = mapper;
        this.properties = properties;
        generatedType = "%s.%sEntityModel".formatted(baseName, type.getSimpleName());

        Map<Class<? extends Annotation>, Annotation> annotations = ClassHierarchy.annotations(standinType);
        this.entityAnnotation = (Entity) annotations.get(Entity.class);
        this.externalEntity = (ExternalEntity) annotations.get(ExternalEntity.class);
        if (this.entityAnnotation == null && this.externalEntity == null) {
            throw new IllegalStateException(
                    "Class %s does not have @Entity or @ExternalEntity annotation".formatted(standinType.getName()));
        }

        // The Morphia annotations of the stand-in, its superclasses and interfaces, in the reflective mapper's precedence.
        // Only Morphia annotations have builders to emit them with, so other annotations are left out.
        List<Annotation> allAnnotations = new ArrayList<>();
        for (Annotation a : annotations.values()) {
            String name = a.annotationType().getName();
            if (name.startsWith("dev.morphia.annotations.") && !name.contains(".internal.")) {
                allAnnotations.add(a);
            }
        }
        // MorphiaDefaultsConvention synthesizes @Entity from @ExternalEntity; mirror that here
        // so that model.getAnnotation(Entity.class) returns non-null for @ExternalEntity models.
        if (this.externalEntity != null && allAnnotations.stream().noneMatch(a -> a instanceof Entity)) {
            allAnnotations.add(entityBuilder()
                    .cap(this.externalEntity.cap())
                    .concern(this.externalEntity.concern())
                    .discriminator(this.externalEntity.discriminator())
                    .discriminatorKey(this.externalEntity.discriminatorKey())
                    .value(this.externalEntity.value())
                    .useDiscriminator(this.externalEntity.useDiscriminator())
                    .build());
        }
        this.morphiaAnnotations = List.copyOf(allAnnotations);
    }

    /**
     * Creates a new entity model generator where the entity class is also the annotation source.
     */
    public EntityModelGenerator(Mapper mapper, Class<?> type, CritterClassLoader critterClassLoader,
            List<PropertyModelGenerator> properties) {
        this(mapper, type, type, critterClassLoader, properties);
    }

    /**
     * @param instantiators the instantiators the model registers
     * @return this generator
     */
    public EntityModelGenerator instantiators(List<InstantiatorGenerator> instantiators) {
        this.instantiators = instantiators;
        return this;
    }

    /**
     * Makes the model a pre-generated one, which checks when it's initialized that it can still be used: that its format is
     * this version's, and that the classes it calls into are still woven as they were when it was generated. It records the
     * configuration it was generated with for the mapper to compare with its own.
     *
     * @param weaveStamps the names of the stamps of the woven classes, which the entity declares or inherits
     * @return this generator
     */
    public EntityModelGenerator pregenerated(List<String> weaveStamps) {
        this.weaveStamps = weaveStamps;
        return this;
    }

    /**
     * Emits the generated entity model class and returns this generator.
     */
    public EntityModelGenerator emit() {
        critterClassLoader.register(generatedType, generate());
        return this;
    }

    /**
     * Generates the entity model class without registering it.
     *
     * @return the class's bytecode
     */
    public byte[] generate() {
        ClassDesc thisDesc = ClassDesc.of(generatedType);
        ClassDesc superDesc = ClassDesc.of(CritterEntityModel.class.getName());
        ClassDesc mapperDesc = ClassDesc.of(Mapper.class.getName());
        ClassDesc entityModelDesc = ClassDesc.of(dev.morphia.mapping.codec.pojo.EntityModel.class.getName());
        ClassDesc annotationDesc = ClassDesc.of(Annotation.class.getName());
        String collectionNameStr = computeCollectionName();
        String discriminatorStr = computeDiscriminator();
        String discriminatorKeyStr = computeDiscriminatorKey();
        boolean useDiscriminatorFlag = entityAnnotation != null ? entityAnnotation.useDiscriminator()
                : externalEntity.useDiscriminator();

        byte[] bytes = ClassFile.of().build(thisDesc, cb -> {
            cb.withVersion(ClassFile.JAVA_17_VERSION, 0);
            cb.withFlags(ClassFile.ACC_PUBLIC | ClassFile.ACC_SUPER);
            cb.withSuperclass(superDesc);

            if (weaveStamps != null) {
                emitValidity(cb, superDesc);
            }

            // each property is built by its own method, so a wide entity doesn't push the constructor past the JVM's
            // limit on a method's size
            for (int i = 0; i < properties.size(); i++) {
                PropertyModelGenerator prop = properties.get(i);
                prop.emitAnnotationHolder(cb);
                cb.withMethodBody(propertyMethod(i), MethodTypeDesc.of(ConstantDescs.CD_void),
                        ClassFile.ACC_PRIVATE | ClassFile.ACC_SYNTHETIC, cod -> {
                            prop.emitProperty(cod, thisDesc, 1);
                            cod.return_();
                        });
            }

            // Constructor: (Mapper) -> void. It configures a plain EntityModel: the generated class overrides nothing.
            cb.withMethodBody("<init>", MethodTypeDesc.of(ConstantDescs.CD_void, mapperDesc),
                    ClassFile.ACC_PUBLIC, cod -> {
                        cod.aload(0);
                        cod.aload(1);
                        GenerationUtils.emitClassRef(cod, entity, thisDesc);
                        cod.invokespecial(superDesc, "<init>",
                                MethodTypeDesc.of(ConstantDescs.CD_void, mapperDesc, ConstantDescs.CD_Class));

                        cod.aload(0);
                        cod.ldc(collectionNameStr);
                        cod.invokevirtual(entityModelDesc, "collectionName",
                                MethodTypeDesc.of(entityModelDesc, ConstantDescs.CD_String));
                        cod.pop();

                        cod.aload(0);
                        cod.ldc(discriminatorStr);
                        cod.invokevirtual(entityModelDesc, "discriminator",
                                MethodTypeDesc.of(ConstantDescs.CD_void, ConstantDescs.CD_String));

                        cod.aload(0);
                        cod.ldc(discriminatorKeyStr);
                        cod.invokevirtual(entityModelDesc, "discriminatorKey",
                                MethodTypeDesc.of(entityModelDesc, ConstantDescs.CD_String));
                        cod.pop();

                        cod.aload(0);
                        cod.loadConstant(useDiscriminatorFlag ? 1 : 0);
                        cod.invokevirtual(entityModelDesc, "discriminatorEnabled",
                                MethodTypeDesc.of(entityModelDesc, ConstantDescs.CD_boolean));
                        cod.pop();

                        for (int i = 0; i < properties.size(); i++) {
                            cod.aload(0);
                            cod.invokespecial(thisDesc, propertyMethod(i), MethodTypeDesc.of(ConstantDescs.CD_void));
                        }

                        // Morphia annotations via builders — no reflection
                        for (Annotation ann : morphiaAnnotations) {
                            cod.aload(0);
                            GenerationUtils.emitAnnotationViaBuilder(cod, ann, thisDesc);
                            cod.invokevirtual(entityModelDesc, "annotation",
                                    MethodTypeDesc.of(ConstantDescs.CD_void, annotationDesc));
                        }

                        for (InstantiatorGenerator instantiator : instantiators) {
                            emitInstantiator(cod, thisDesc, entityModelDesc, instantiator);
                        }

                        // configureProperties(mapper)
                        cod.aload(0);
                        cod.aload(1);
                        cod.invokevirtual(thisDesc, "configureProperties",
                                MethodTypeDesc.of(ConstantDescs.CD_void, mapperDesc));

                        cod.return_();
                    });
        });

        return bytes;
    }

    /**
     * Emits the generation key field, and a static initializer checking the format and that every weave stamp is still
     * there. A stamp that's missing because its class was compiled again without being woven, or woven differently, fails
     * with a {@link NoSuchFieldError}.
     */
    private void emitValidity(ClassBuilder cb, ClassDesc superDesc) {
        String generationKey = CritterEntityModel.generationKey(mapper.getConfig());
        cb.withField(CritterEntityModel.GENERATION_KEY, ConstantDescs.CD_String, fb -> fb
                .withFlags(ClassFile.ACC_PUBLIC | ClassFile.ACC_STATIC | ClassFile.ACC_FINAL | ClassFile.ACC_SYNTHETIC)
                .with(ConstantValueAttribute.of(generationKey)));
        ClassDesc thisDesc = ClassDesc.of(generatedType);
        cb.withMethodBody("<clinit>", MethodTypeDesc.of(ConstantDescs.CD_void), ClassFile.ACC_STATIC, cod -> {
            cod.loadConstant(CritterEntityModel.FORMAT);
            cod.invokestatic(superDesc, "checkFormat", MethodTypeDesc.of(ConstantDescs.CD_void, ConstantDescs.CD_int));
            // through the entity, which inherits the stamps of the superclasses woven with it
            GenerationUtils.emitClassRef(cod, entity, thisDesc);
            for (String stamp : weaveStamps) {
                cod.dup();
                cod.ldc(stamp);
                cod.invokestatic(superDesc, "checkWoven",
                        MethodTypeDesc.of(ConstantDescs.CD_void, ConstantDescs.CD_Class, ConstantDescs.CD_String));
            }
            cod.pop();
            cod.return_();
        });
    }

    /**
     * Emits {@code instantiator(descriptor, instance)}, taking a runtime instantiator from {@link NestmateAccessorRegistry}.
     */
    private static void emitInstantiator(CodeBuilder cod, ClassDesc thisDesc, ClassDesc entityModelDesc,
            InstantiatorGenerator instantiator) {
        ClassDesc instantiatorDesc = ClassDesc.of(Instantiator.class.getName());
        cod.aload(0);
        cod.ldc(instantiator.constructorDescriptor());
        if (instantiator.isRuntime()) {
            ClassDesc classLoaderDesc = ClassDesc.of(ClassLoader.class.getName());
            cod.ldc(thisDesc);
            cod.invokevirtual(ConstantDescs.CD_Class, "getClassLoader", MethodTypeDesc.of(classLoaderDesc));
            cod.ldc(instantiator.registryKey);
            cod.invokestatic(ClassDesc.of(NestmateAccessorRegistry.class.getName()), "instantiator",
                    MethodTypeDesc.of(instantiatorDesc, classLoaderDesc, ConstantDescs.CD_String));
        } else {
            ClassDesc implDesc = ClassDesc.of(instantiator.getGeneratedType());
            cod.new_(implDesc);
            cod.dup();
            cod.invokespecial(implDesc, "<init>", MethodTypeDesc.of(ConstantDescs.CD_void));
        }
        cod.invokevirtual(entityModelDesc, "instantiator",
                MethodTypeDesc.of(ConstantDescs.CD_void, ConstantDescs.CD_String, instantiatorDesc));
    }

    private static String propertyMethod(int index) {
        return "__property" + index;
    }

    private String computeCollectionName() {
        String key = entityAnnotation != null ? entityAnnotation.value() : externalEntity.value();
        return Mapper.IGNORED_FIELDNAME.equals(key)
                ? mapper.getConfig().collectionNaming().apply(entity.getSimpleName())
                : key;
    }

    private String computeDiscriminator() {
        String disc = entityAnnotation != null ? entityAnnotation.discriminator() : externalEntity.discriminator();
        return mapper.getConfig().discriminator().apply(entity, disc);
    }

    private String computeDiscriminatorKey() {
        String key = entityAnnotation != null ? entityAnnotation.discriminatorKey() : externalEntity.discriminatorKey();
        return Mapper.IGNORED_FIELDNAME.equals(key)
                ? mapper.getConfig().discriminatorKey()
                : key;
    }

}
